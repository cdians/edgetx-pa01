#!/usr/bin/env python3
"""Render the PA01 charge-screen captions into an 8-bit alpha mask header.

The charge screen draws straight into the panel frame buffer, before LVGL (and
therefore before any font engine) exists. So the two captions are baked here
into plain byte-per-pixel alpha masks and blitted by hand at run time.

Usage:
    gen_charge_text.py <out.h> [--size 44] [--font C:/Windows/Fonts/msyhbd.ttc]
"""

import argparse
import os

from PIL import Image, ImageDraw, ImageFont

CAPTIONS = [
    ("chargeTextCharging", "CHARGE_TEXT_CHARGING", "充电中"),
    ("chargeTextFull", "CHARGE_TEXT_FULL", "电量已满"),
]


def render(text, font, target_h):
    # Render generously, then crop to the ink box so the glyphs sit tight in the
    # mask - that keeps the vertical placement in C predictable.
    pad = target_h
    probe = Image.new("L", (target_h * (len(text) + 2), target_h * 3), 0)
    ImageDraw.Draw(probe).text((pad, pad), text, font=font, fill=255)
    bbox = probe.getbbox()
    if bbox is None:
        raise SystemExit("empty glyph box for %r" % text)

    img = probe.crop(bbox)
    # Grow to an even width so the caller can round the centring cleanly.
    if img.width % 2:
        wide = Image.new("L", (img.width + 1, img.height), 0)
        wide.paste(img, (0, 0))
        img = wide
    return img


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--size", type=int, default=44)
    ap.add_argument("--font", default=r"C:\Windows\Fonts\msyhbd.ttc")
    args = ap.parse_args()

    font = ImageFont.truetype(args.font, args.size)

    lines = [
        "// Generated by build-tools/gen_charge_text.py - do not edit.",
        "//",
        "// 8-bit alpha coverage masks for the PA01 charge captions. The charge",
        "// screen runs before LVGL exists, so there is no font engine to borrow:",
        "// these are blitted straight into the panel frame buffer.",
        "",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
    ]

    for name, macro, text in CAPTIONS:
        img = render(text, font, args.size)
        w, h = img.size
        data = img.tobytes()

        lines.append("// %s  (%d x %d)" % (text, w, h))
        lines.append("#define %s_W %d" % (macro, w))
        lines.append("#define %s_H %d" % (macro, h))
        lines.append("static const uint8_t %s[] = {" % name)

        for y in range(h):
            row = data[y * w:(y + 1) * w]
            lines.append("  " + ",".join("%3d" % v for v in row) + ",")
        lines.append("};")
        lines.append("")

        preview = os.path.splitext(args.out)[0] + "_%s.png" % name
        img.save(preview)
        print("%-22s %3dx%-3d -> %s" % (text, w, h, preview))

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print("header:", args.out)


if __name__ == "__main__":
    main()
